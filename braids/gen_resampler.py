"""Generate braids/resample_taps.h: 96 kHz -> 44117.647 Hz polyphase filter.

Ratio 96000 / (750000/17) = 272/125: 125 phases x 32 taps of a Kaiser-windowed
sinc low-pass designed at the 125x upsampled rate (cutoff 20 kHz, beta 7).
Each phase is normalised to unity DC gain and stored as Q15, reversed
(oldest input first) so the filter can run forward over the input in 16-bit
pairs with the M4's dual multiply-accumulate (SMLAD).
Usage: python3 braids/gen_resampler.py > braids/resample_taps.h
"""
import math

PHASES, TAPS = 125, 32
FS_IN = 96000.0
CUTOFF = 20000.0
BETA = 7.0


def i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s


n = PHASES * TAPS
center = (n - 1) / 2.0
fc = CUTOFF / (FS_IN * PHASES)          # normalised to the upsampled rate
proto = []
for i in range(n):
    x = i - center
    sinc = 2 * fc if x == 0 else math.sin(2 * math.pi * fc * x) / (math.pi * x)
    w = i0(BETA * math.sqrt(max(0.0, 1 - (x / center) ** 2))) / i0(BETA)
    proto.append(sinc * w)

print("// Generated by braids/gen_resampler.py: 96 kHz -> 44117.647 Hz (272/125),")
print(f"// {PHASES} phases x {TAPS} taps, Kaiser beta {BETA}, cutoff {CUTOFF:.0f} Hz, Q15.")
print("#pragma once")
print("#include <stdint.h>")
print(f"#define RESAMPLE_PHASES {PHASES}")
print(f"#define RESAMPLE_TAPS {TAPS}")
print(f"#define RESAMPLE_STEP 272   // input positions (in 1/{PHASES}) per output")
print(f"__attribute__((aligned(4))) static const int16_t kResampleTaps[{PHASES}][{TAPS}] = {{")
for p in range(PHASES):
    taps = [proto[p + PHASES * t] for t in range(TAPS)]
    g = sum(taps)
    q = [int(round(v / g * 32767)) for v in taps][::-1]   # oldest first
    print("  {" + ", ".join(str(v) for v in q) + "},")
print("};")
